func findMaxAverage(nums []int, k int) float64 {
	left := 0
	right := 0
	avg := float64(nums[0])
	max := 0.0
	for right < len(nums) {
		if right >= k {
			prev := float64(nums[left-1])
			avg = ((avg * float64(k)) - prev + float64(nums[right])) / float64(k)
		} else {
			avg = (avg*float64(right) + float64(nums[right])) / (float64(right-left) + 1.0)
		}

		if right == k-1 || right >= k && avg > max {
			max = avg
		}
		if right-left+1 == k {
			left++
		}
		right++
	}

	return max
}

